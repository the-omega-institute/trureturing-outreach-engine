"""CPython 3.12 / Unicode 15.0 scalar contracts, independent of Rust's Unicode.

Ranges partition *every* code point by category and str.isprintable(). Surrogates
are recorded but have no Rust char representation. Casefold vectors include every
changed scalar; all others must map to themselves.
"""
import unicodedata


def vectors():
    if unicodedata.unidata_version != '15.0.0':
        raise RuntimeError('Generate Unicode vectors with Python 3.12 (Unicode 15.0.0)')
    ranges = []
    folds = []
    for cp in range(0x110000):
        ch = chr(cp)
        category, printable = unicodedata.category(ch), ch.isprintable()
        if ranges and ranges[-1]['end'] == cp - 1 and (ranges[-1]['category'], ranges[-1]['printable']) == (category, printable):
            ranges[-1]['end'] = cp
            ranges[-1]['last_repr'] = repr(ch)
        else:
            ranges.append(dict(start=cp, end=cp, category=category, printable=printable,
                               first_repr=repr(ch), last_repr=repr(ch)))
        if ch.casefold() != ch:
            folds.append([cp, ch.casefold()])
    return dict(unicode_version=unicodedata.unidata_version, ranges=ranges, casefold=folds)


def sources(value):
    head = '// Generated by vectors/generate.py with CPython 3.12, Unicode 15.0.0.\n'
    # Full mapping, not exceptions to Rust lowercase: newer Rust Unicode must
    # not change even an unchanged code point in this pinned contract.
    escape = lambda s: ''.join('\\u{' + format(ord(c), 'x') + '}' for c in s)
    folds = head + 'match c {\n' + ''.join(
        "'\\u{%x}' => \"%s\".chars().collect::<Vec<_>>(),\n" % (cp, escape(s))
        for cp, s in value['casefold']) + '_ => vec![c],\n}\n'
    nonprint = []
    for r in value['ranges']:
        if r['printable']:
            continue
        if nonprint and nonprint[-1][1] + 1 == r['start']:
            nonprint[-1][1] = r['end']
        else:
            nonprint.append([r['start'], r['end']])
    printable = head + '&[\n' + ''.join('    (0x%x, 0x%x),\n' % (a, b) for a, b in nonprint) + ']\n'
    return {'casefold.rs': folds, 'nonprintable.rs': printable}
